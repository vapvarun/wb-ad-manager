#!/usr/bin/env bash
# bin/run-journeys.sh — orchestrate journey audits for WB Ad Manager (FREE).
#
# Each journey under audit/journeys/**/*.md is a self-contained
# customer-flow contract. This script enumerates them, builds a runbook
# JSON pointing at $SITE_URL, and writes results to
# audit/journey-runs/{YYYY-MM-DD-HHMM}/.
#
# Usage:
#   bash bin/run-journeys.sh                       # all journeys (writes runbook for an agent)
#   bash bin/run-journeys.sh --site http://other   # different site
#   bash bin/run-journeys.sh --only customer/03    # one journey by slug fragment
#   bash bin/run-journeys.sh --priority critical   # filter by frontmatter priority
#   bash bin/run-journeys.sh --dry-run             # list what would run, no exec
#   bash bin/run-journeys.sh --smoke               # validate environment is journey-ready
#                                                  # (HTTP, REST namespace, DB tables, mu-plugin,
#                                                  # frontmatter parseability). Pure shell, no agent.
#
# Two modes:
#   1. SMOKE  — fast, deterministic, CI-friendly. Validates the journeys
#      CAN run (preconditions hold) without actually driving Playwright.
#      Exit 0 means "the environment is journey-ready," not "all
#      assertions pass." Used by `composer journeys:critical` so the
#      gate runs in unattended CI.
#   2. RUNBOOK (default) — writes a JSON manifest of journeys + their
#      paths, then prints the agent prompt. A claude-code session with
#      Playwright MCP + mysql_query MCP loaded executes it. Full
#      browser+REST+DB coverage but requires an interactive agent.
#
# Generated by wp-plugin-onboard skill. Edit freely.

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PLUGIN_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$PLUGIN_DIR"

SITE_URL="${LOCAL_CI_SITE_URL:-http://wp-ads.local}"
ONLY=""
PRIORITY=""
DRY_RUN=0
SMOKE=0

while [ $# -gt 0 ]; do
  case "$1" in
    --site)     SITE_URL="$2"; shift ;;
    --only)     ONLY="$2"; shift ;;
    --priority) PRIORITY="$2"; shift ;;
    --dry-run)  DRY_RUN=1 ;;
    --smoke)    SMOKE=1 ;;
    *) echo "Unknown flag: $1"; exit 2 ;;
  esac
  shift
done

# Detect a Local-by-Flywheel site root from $SITE_URL so smoke mode can
# resolve plugin/mu-plugin paths and the WP-CLI socket without flags.
SITE_HOST="$(printf '%s' "$SITE_URL" | sed -E 's#^https?://##; s#/.*$##')"
LOCAL_SITES_ROOT="${LOCAL_SITES_ROOT:-$HOME/Local Sites}"
SITE_ROOT=""
if [ -d "$LOCAL_SITES_ROOT" ]; then
  # Prefer host-name match, then site-name match.
  for candidate in "$LOCAL_SITES_ROOT"/*/app/public; do
    [ -d "$candidate" ] || continue
    name="$(basename "$(dirname "$(dirname "$candidate")")")"
    if [ "$name" = "${SITE_HOST%.local}" ] || [ "$name" = "$SITE_HOST" ]; then
      SITE_ROOT="$candidate"
      break
    fi
  done
fi

# ─── Discover journeys ───────────────────────────────────────────────────────

JOURNEYS=()
while IFS= read -r -d '' f; do
  rel="${f#$PLUGIN_DIR/}"
  if [ -n "$ONLY" ] && [[ "$rel" != *"$ONLY"* ]]; then
    continue
  fi
  if [ -n "$PRIORITY" ]; then
    actual_priority=$(awk '/^priority:/ { print $2; exit }' "$f")
    [ "$actual_priority" = "$PRIORITY" ] || continue
  fi
  JOURNEYS+=("$rel")
done < <(find audit/journeys -type f -name '*.md' -not -name 'README.md' -not -name '.template.md' -not -name '_template.md' -print0 | sort -z)

if [ ${#JOURNEYS[@]} -eq 0 ]; then
  echo "No journeys matched filter (only=$ONLY priority=$PRIORITY)"
  exit 0
fi

# ─── Smoke mode ──────────────────────────────────────────────────────────────
#
# Validates the journey-runner's environment: site reachable, REST
# namespace responsive, declared DB tables exist, dev-auto-login
# mu-plugin present, and every filtered journey has parseable
# frontmatter. Does NOT execute the journeys' Playwright steps —
# that's the runbook mode below.
#
# Designed for `composer journeys:critical` in CI: deterministic,
# fast (~5s on a Local install), no MCP / agent / browser needed.

if [ "$SMOKE" = "1" ]; then
  echo "=== Journey smoke-check ==="
  echo "Site:     $SITE_URL"
  [ -n "$SITE_ROOT" ] && echo "WP root:  $SITE_ROOT"
  echo "Filter:   ${PRIORITY:-all}${ONLY:+ +only=$ONLY}"
  echo "Journeys: ${#JOURNEYS[@]}"
  echo ""

  fail=0
  pass_n=0
  warn_n=0

  check_pass () { printf "  \033[32m✓\033[0m %s\n" "$1"; pass_n=$((pass_n + 1)); }
  check_warn () { printf "  \033[33m⚠\033[0m %s — %s\n" "$1" "$2"; warn_n=$((warn_n + 1)); }
  check_fail () { printf "  \033[31m✗\033[0m %s — %s\n" "$1" "$2"; fail=1; }

  # 1. HTTP reachability (HEAD; follow redirects).
  http_code=$(curl -s -o /dev/null -w "%{http_code}" -L --max-time 10 "$SITE_URL/" 2>/dev/null || echo "000")
  if [ "$http_code" = "200" ]; then
    check_pass "site HTTP 200 ($SITE_URL)"
  elif [ "$http_code" = "301" ] || [ "$http_code" = "302" ]; then
    check_pass "site reachable (HTTP $http_code, redirected)"
  else
    check_fail "site HTTP $http_code" "expected 200/301/302"
  fi

  # 2. REST namespace — read the plugin's own namespace from manifest.json
  #    so FREE (wbam/v1) and PRO (wbam-pro/v1) check the right route.
  rest_ns=""
  if [ -f "audit/manifest.json" ] && command -v jq >/dev/null 2>&1; then
    rest_ns=$(jq -r '.rest.namespace // empty' audit/manifest.json 2>/dev/null)
  fi
  if [ -z "$rest_ns" ]; then
    check_warn "REST namespace check" "manifest/jq unavailable — could not derive namespace; skipping"
  else
    ns_code=$(curl -s -o /dev/null -w "%{http_code}" -L --max-time 10 "$SITE_URL/wp-json/$rest_ns" 2>/dev/null || echo "000")
    if [ "$ns_code" = "200" ] || [ "$ns_code" = "401" ] || [ "$ns_code" = "404" ]; then
      # 401 = endpoint exists but auth required (still proves namespace registered).
      # 404 = empty namespace OK as long as REST itself responds (checked next).
      rest_root=$(curl -s -o /dev/null -w "%{http_code}" -L --max-time 10 "$SITE_URL/wp-json/" 2>/dev/null || echo "000")
      if [ "$rest_root" = "200" ]; then
        check_pass "REST namespace $rest_ns reachable (HTTP $ns_code)"
      else
        check_fail "REST root /wp-json/ returned $rest_root" "WordPress REST disabled?"
      fi
    else
      check_fail "REST namespace $rest_ns returned HTTP $ns_code" "expected 200/401/404"
    fi
  fi

  # 3. dev-auto-login mu-plugin (required by every journey's Setup section).
  if [ -n "$SITE_ROOT" ] && [ -f "$SITE_ROOT/wp-content/mu-plugins/dev-auto-login.php" ]; then
    check_pass "dev-auto-login mu-plugin present"
  elif [ -z "$SITE_ROOT" ]; then
    check_warn "dev-auto-login mu-plugin" "could not resolve site root from $SITE_URL — skipping"
  else
    check_fail "dev-auto-login mu-plugin missing" "$SITE_ROOT/wp-content/mu-plugins/dev-auto-login.php"
  fi

  # 4. Declared DB tables (from manifest.json) exist.
  #    Fail-soft: WP-CLI without Local-by-Flywheel's shell wrapper can't
  #    reach the per-site MySQL socket. We probe with a single SHOW TABLES
  #    call first; if it errors, downgrade the whole table check to a
  #    warning rather than failing the gate. Inside Local's shell (where
  #    `wp` resolves the right socket) the check runs to completion.
  if [ -f "audit/manifest.json" ] && command -v jq >/dev/null 2>&1 && [ -n "$SITE_ROOT" ]; then
    probe=$(cd "$SITE_ROOT" && wp db query "SELECT 1" --skip-plugins --skip-themes --skip-column-names 2>&1)
    if printf '%s' "$probe" | grep -qi "Can't connect\|Access denied\|2002\|MySQL server has gone away"; then
      check_warn "DB-table check" "WP-CLI can't reach MySQL outside Local-by-Flywheel's shell — run from Local's terminal to validate"
    else
      # Manifest stores names as either bare strings or {name, purpose} objects.
      # `.name // .` picks the field on objects, falls through to the value on
      # bare strings. Strip the `{prefix}` placeholder so the WP-CLI lookup
      # below adds the live prefix.
      declared_tables=$(jq -r '.tables[]? | (if type == "string" then . else .name end) // empty' audit/manifest.json 2>/dev/null \
        | sed -e 's/^{prefix}//' \
        | grep -E "^wbam_" | sort -u)
      if [ -z "$declared_tables" ]; then
        check_warn "DB-table check" "manifest had no .tables[] entries"
      else
        missing=""
        while IFS= read -r tbl; do
          [ -z "$tbl" ] && continue
          exists=$(cd "$SITE_ROOT" && wp db query "SHOW TABLES LIKE 'wp_${tbl}'" --skip-plugins --skip-themes --skip-column-names 2>/dev/null | head -1)
          if [ -z "$exists" ]; then
            missing="$missing $tbl"
          fi
        done <<< "$declared_tables"
        n_declared=$(echo "$declared_tables" | wc -l | tr -d ' ')
        if [ -z "$missing" ]; then
          check_pass "all $n_declared declared DB tables exist"
        else
          check_fail "missing DB tables" "${missing# }"
        fi
      fi
    fi
  else
    check_warn "DB-table check" "manifest/jq/site-root unavailable; skipping"
  fi

  # 5. Per-journey frontmatter parses + has the required fields.
  bad_yaml=""
  for j in "${JOURNEYS[@]}"; do
    slug=$(awk '/^journey:/ { print $2; exit }' "$j")
    priority=$(awk '/^priority:/ { print $2; exit }' "$j")
    if [ -z "$slug" ] || [ -z "$priority" ]; then
      bad_yaml="$bad_yaml\n    $j (slug='${slug}' priority='${priority}')"
    fi
  done
  if [ -z "$bad_yaml" ]; then
    check_pass "${#JOURNEYS[@]} journey frontmatters parse + carry slug+priority"
  else
    check_fail "bad frontmatter" "$(printf '%b' "$bad_yaml")"
  fi

  echo ""
  if [ "$fail" -eq 0 ]; then
    printf "\033[32mSmoke check passed.\033[0m  %d checks ok, %d warnings.\n" "$pass_n" "$warn_n"
    echo "Environment is journey-ready. Run the full runbook (without --smoke) to drive Playwright via an agent."
    exit 0
  else
    printf "\033[31mSmoke check FAILED.\033[0m  %d ok, %d warnings, plus the failures above.\n" "$pass_n" "$warn_n"
    echo "Fix the environment before driving the full runbook."
    exit 1
  fi
fi

# ─── Build the runbook ───────────────────────────────────────────────────────

RUN_ID="$(date +%Y-%m-%d-%H%M)"
RUN_DIR="audit/journey-runs/$RUN_ID"
mkdir -p "$RUN_DIR"

RUNBOOK="$RUN_DIR/runbook.json"
{
  printf '{\n'
  printf '  "run_id": "%s",\n' "$RUN_ID"
  printf '  "site": "%s",\n' "$SITE_URL"
  printf '  "started_at": "%s",\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  printf '  "journeys": [\n'
  for i in "${!JOURNEYS[@]}"; do
    j="${JOURNEYS[$i]}"
    slug=$(awk '/^journey:/ { print $2; exit }' "$j")
    priority=$(awk '/^priority:/ { print $2; exit }' "$j")
    printf '    { "slug": "%s", "priority": "%s", "path": "%s" }' "$slug" "$priority" "$j"
    [ "$i" -lt $((${#JOURNEYS[@]} - 1)) ] && printf ','
    printf '\n'
  done
  printf '  ]\n}\n'
} > "$RUNBOOK"

echo "=== WB Ad Manager Pro journeys ==="
echo "Run ID: $RUN_ID"
echo "Site:   $SITE_URL"
echo "Found:  ${#JOURNEYS[@]} journeys"
echo ""
for j in "${JOURNEYS[@]}"; do
  slug=$(awk '/^journey:/ { print $2; exit }' "$j")
  priority=$(awk '/^priority:/ { print $2; exit }' "$j")
  printf "  [%-9s] %s  (%s)\n" "$priority" "$slug" "$j"
done
echo ""

if [ "$DRY_RUN" = "1" ]; then
  echo "Dry run — exiting before execution. Runbook at $RUNBOOK"
  exit 0
fi

# ─── Execution path ──────────────────────────────────────────────────────────
#
# Journeys are executed by an agent that has Playwright + curl + MySQL
# access. Today the integration is manual: feed the runbook to a
# claude-code session that has the relevant MCPs loaded:
#
#   claude-code "Run journeys per $RUNBOOK — for each, read the journey \
#     markdown, execute every step against $SITE_URL using the playwright \
#     MCP and curl/mysql, then write $RUN_DIR/{slug}.json with the schema \
#     in audit/journeys/README.md"
#
# When wppqa_run_journeys MCP tool ships, this script will invoke it
# directly. Until then, a regression sentinel: if the most recent prior
# run has any FAIL journeys, fail this run too.

echo "Runbook written to: $RUNBOOK"
echo ""
echo "Execute via journey-aware agent. Suggested prompt:"
echo "  Run all journeys in $RUNBOOK against $SITE_URL. For each: read"
echo "  the markdown, execute every step (Playwright + curl + mysql),"
echo "  write $RUN_DIR/{slug}.json. Aggregate to $RUN_DIR/summary.json."
echo ""

LATEST_PRIOR=$(ls -1 audit/journey-runs/ 2>/dev/null | grep -v "$RUN_ID" | tail -1 || echo "")
if [ -n "$LATEST_PRIOR" ] && [ -f "audit/journey-runs/$LATEST_PRIOR/summary.json" ]; then
  PRIOR_FAIL=$(jq -r '.failed // 0' "audit/journey-runs/$LATEST_PRIOR/summary.json" 2>/dev/null || echo "0")
  if [ "$PRIOR_FAIL" -gt 0 ]; then
    echo "Most recent prior run ($LATEST_PRIOR) had $PRIOR_FAIL failed journeys."
    echo "Run them again and ship a fix before merging."
    exit 1
  fi
fi

exit 0
